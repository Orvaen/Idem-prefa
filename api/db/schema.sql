-- Schéma PostgreSQL de l'application de préfabrication IDEM : la base de l'API (Bun).
--
-- Traduction de db/schema.sql (MySQL) : mêmes tables, mêmes colonnes, mêmes contraintes,
-- mêmes données de référence. Les différences, toutes voulues :
--
--   * Les noms sont en minuscules. Postgres replie en minuscules tout nom écrit sans
--     guillemets : « Utilisateur » devient utilisateur, « idUsers » idusers, « CDN » cdn.
--     Dans une requête, FROM Utilisateur marche encore ; mais les lignes reviennent avec
--     des clés en minuscules (row.idusers, pas row.idUsers).
--   * La colonne « QMOS » de MySQL, qui avait une espace en tête de son nom, s'appelle qmos.
--   * tinyint(1) devient boolean. affectation_atelier.actif garde son principe :
--     true = l'affectation en cours, NULL = terminée.
--   * Les enum deviennent du texte avec un CHECK : ajouter une valeur se fait par un
--     ALTER TABLE ordinaire, sans type à modifier.
--   * MySQL comparait sans tenir compte de la casse ni des accents (utf8mb4_0900_ai_ci).
--     Postgres en tient compte. L'identifiant, le courriel et le nom d'affaire sont en
--     citext, pour que « Rayan » retrouve « rayan » à la connexion comme avant, et que
--     deux affaires ne diffèrent pas que par une majuscule. Ailleurs, chercher sans la
--     casse demande ILIKE au lieu de LIKE.
--   * datetime devient timestamptz : un instant absolu, que Bun rend en Date.
--   * Les entiers non signés n'existent pas : tinyint unsigned devient smallint, smallint
--     unsigned devient integer. int unsigned et bigint unsigned deviennent integer aussi :
--     deux milliards suffisent ici, et Bun rendrait un bigint en chaîne ("12" et non 12).
--   * decimal devient numeric. Bun le rend en chaîne, pour ne rien perdre en précision.
--   * longblob, mediumblob et binary deviennent bytea.
--
-- Installation sur une base vide : run schema-pg
--
-- Tout se passe dans une transaction : sur une base qui a déjà ses tables, la première
-- création échoue et rien n'est gardé, ni table ni donnée de référence.

