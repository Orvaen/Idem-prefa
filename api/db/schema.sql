BEGIN;

CREATE EXTENSION IF NOT EXISTS citext;


-- ---------------------------------------------------------------------------------------
-- Les tables de référence
-- ---------------------------------------------------------------------------------------

CREATE TABLE role (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL
);

CREATE TABLE statut_demande (
  id      integer PRIMARY KEY,
  libelle varchar(40) NOT NULL UNIQUE
);

CREATE TABLE type_matiere (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  libelle varchar(100) NOT NULL UNIQUE
);

CREATE TABLE type_passivation (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  libelle varchar(100) NOT NULL
);

CREATE TABLE unite_materiel (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  libelle varchar(16) NOT NULL UNIQUE
);

-- Sans clé primaire, comme dans MySQL.
CREATE TABLE revetements (
  id      integer NOT NULL,
  libelle varchar(100) NOT NULL
);

CREATE TABLE parametrage_prefabrication (
  id               smallint PRIMARY KEY,
  heures_par_pouce numeric(8,4) NOT NULL DEFAULT 1,
  duree_heures     integer NOT NULL DEFAULT 1,
  duree_minutes    smallint NOT NULL DEFAULT 0
);


-- ---------------------------------------------------------------------------------------
-- Les comptes
-- ---------------------------------------------------------------------------------------

CREATE TABLE utilisateur (
  id                           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                         varchar(100) NOT NULL,
  id_role                      integer NOT NULL,
  password                     varchar(100) NOT NULL,
  reinitialisation_demandee_le timestamptz,
  email                        citext UNIQUE CHECK (char_length(email) <= 255),
  prenom                       varchar(256) NOT NULL,
  identifiant                  citext NOT NULL CHECK (char_length(identifiant) <= 256),
  date_creation                timestamptz DEFAULT now(),
  dernier_evenement_vu         integer NOT NULL DEFAULT 0
);
COMMENT ON COLUMN utilisateur.reinitialisation_demandee_le IS 'la personne demande un nouveau mot de passe — oublié, ou à changer : l''administrateur réinitialise ; NULL sinon';
COMMENT ON COLUMN utilisateur.dernier_evenement_vu IS 'le dernier événement que la personne a vu sur son accueil';

CREATE TABLE signature_utilisateur (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_utilisateur integer NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
  dessin         jsonb NOT NULL,
  date_creation  timestamptz NOT NULL DEFAULT now(),
  date_retrait   timestamptz
);
CREATE INDEX ON signature_utilisateur (id_utilisateur);
COMMENT ON COLUMN signature_utilisateur.dessin IS 'les traits, en hauteurs de signature : {"proportion":3.2,"traits":[[[x,y],…],…]}';
COMMENT ON COLUMN signature_utilisateur.date_retrait IS 'refaite ou supprimée ce jour-là ; NULL : la signature en cours';


-- ---------------------------------------------------------------------------------------
-- Les affaires et les demandes de préfabrication
-- ---------------------------------------------------------------------------------------

CREATE TABLE charger_affaier (
  id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom varchar(255) NOT NULL
);

CREATE TABLE affaire (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom               citext NOT NULL UNIQUE CHECK (char_length(nom) <= 255),
  id_charge_affaire integer REFERENCES utilisateur (id) ON DELETE SET NULL,
  date_creation     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON affaire (id_charge_affaire);
COMMENT ON COLUMN affaire.id_charge_affaire IS 'Le chargé d''affaire, rôle 5';

CREATE TABLE demande_prefabrication (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idusers                 integer NOT NULL,
  dateupdate              timestamptz NOT NULL,
  date_creation           timestamptz,
  date_livraison_prevue   date,
  date_fin_prevue         date,
  nom_affaire             varchar(255),
  id_affaire              integer REFERENCES affaire (id) ON DELETE SET NULL,
  plan_bpe_iso            varchar(255),
  pouces_total_iso        integer NOT NULL,
  heures_chiffrees        numeric(15,2) NOT NULL DEFAULT 0,
  cdn                     boolean NOT NULL,
  qmos                    varchar(255) NOT NULL,
  urgent                  boolean NOT NULL,
  id_statut               integer NOT NULL DEFAULT 1 REFERENCES statut_demande (id),
  controles_cdn           varchar(1000),
  commentaire_validation  varchar(1000),
  valide_par              integer,
  date_validation         timestamptz,
  id_passivation          integer REFERENCES type_passivation (id),
  revetement              boolean NOT NULL DEFAULT false,
  commentaire_revetement  varchar(1000),
  id_matiere              integer REFERENCES type_matiere (id),
  matiere_disponibilite   text CHECK (matiere_disponibilite IN ('stock', 'commande')),
  rt                      boolean NOT NULL DEFAULT false,
  pt                      boolean NOT NULL DEFAULT false,
  controles_rt            numeric(5,2),
  controles_pt            numeric(5,2),
  id_charger_affaire      integer REFERENCES utilisateur (id) ON DELETE SET NULL,
  date_debut_planifiee    date,
  date_fin_planifiee      date,
  planning_jours_ouvres   boolean NOT NULL DEFAULT true,
  planning_revision       integer NOT NULL DEFAULT 0,
  id_personnel_atelier    integer REFERENCES utilisateur (id),
  date_prise_en_charge    timestamptz,
  prise_en_charge_atelier boolean NOT NULL DEFAULT false,
  pris_en_charge_par      integer REFERENCES utilisateur (id)
);
CREATE INDEX ON demande_prefabrication (idusers);
CREATE INDEX ON demande_prefabrication (id_passivation);
CREATE INDEX ON demande_prefabrication (id_matiere);
CREATE INDEX ON demande_prefabrication (id_charger_affaire);
CREATE INDEX ON demande_prefabrication (id_statut, id_charger_affaire, date_debut_planifiee, date_fin_planifiee);
CREATE INDEX ON demande_prefabrication (id_personnel_atelier);
CREATE INDEX ON demande_prefabrication (pris_en_charge_par);
CREATE INDEX ON demande_prefabrication (id_affaire);
COMMENT ON COLUMN demande_prefabrication.id IS 'id de la table';
COMMENT ON COLUMN demande_prefabrication.idusers IS 'clé secondaire relier à la table utilisateur';
COMMENT ON COLUMN demande_prefabrication.dateupdate IS 'Date de la mise à jours de la demande';
COMMENT ON COLUMN demande_prefabrication.cdn IS 'Si oui alors communiquer le pourcentage par contrôle';

