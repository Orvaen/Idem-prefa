  nom        varchar(255) NOT NULL,
  contenu    bytea NOT NULL,
  sha256     bytea NOT NULL CHECK (octet_length(sha256) = 32)
);
CREATE INDEX ON demande_qmos_documents (id_demande);

CREATE TABLE demande_dmos (
  id_demande integer PRIMARY KEY REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  nom        varchar(255) NOT NULL,
  contenu    bytea NOT NULL
);

CREATE TABLE demande_dmos_documents (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_demande integer NOT NULL REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  nom        varchar(255) NOT NULL,
  contenu    bytea NOT NULL,
  sha256     bytea NOT NULL CHECK (octet_length(sha256) = 32)
);
CREATE INDEX ON demande_dmos_documents (id_demande);

CREATE TABLE demande_ccpu_documents (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_demande   integer NOT NULL REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  nom          varchar(255) NOT NULL,
  contenu      bytea NOT NULL,
  sha256       bytea NOT NULL CHECK (octet_length(sha256) = 32),
  lecture      varchar(10),
  erreur       varchar(255),
  date_lecture timestamptz,
  certificat   varchar(40),
  dimensions   varchar(255),
  nuances      varchar(255)
);
CREATE INDEX ON demande_ccpu_documents (id_demande);

CREATE TABLE demande_ccpu_coulees (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_document integer NOT NULL REFERENCES demande_ccpu_documents (id) ON DELETE CASCADE,
  numero      varchar(20) NOT NULL,
  page        integer NOT NULL DEFAULT 1,
  confiance   smallint NOT NULL DEFAULT 0,
  confirmee   boolean NOT NULL DEFAULT false,
  UNIQUE (id_document, numero)
);

CREATE TABLE demande_materiel_documents (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_demande        integer NOT NULL REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  nom               varchar(255) NOT NULL,
  contenu           bytea NOT NULL,
  sha256            bytea NOT NULL CHECK (octet_length(sha256) = 32),
  lecture           varchar(10),
  erreur            varchar(255),
  date_lecture      timestamptz,
  numero_commande   varchar(40),
  date_commande     date,
  verifie_par       integer REFERENCES utilisateur (id) ON DELETE SET NULL,
  date_verification timestamptz
);
CREATE INDEX ON demande_materiel_documents (id_demande);
CREATE INDEX ON demande_materiel_documents (verifie_par);
COMMENT ON COLUMN demande_materiel_documents.numero_commande IS 'numéro lu dans l''en-tête du bon';

CREATE TABLE demande_materiel_lignes (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_document     integer NOT NULL REFERENCES demande_materiel_documents (id) ON DELETE CASCADE,
  rang            integer NOT NULL DEFAULT 0,
  page            integer NOT NULL DEFAULT 1,
  reference       varchar(80),
  designation     varchar(180) NOT NULL,
  unite           varchar(16) NOT NULL DEFAULT 'u',
  quantite        numeric(12,3) NOT NULL,
  date_livraison  date,
  confiance       smallint NOT NULL DEFAULT 0,
  douteuse        boolean NOT NULL DEFAULT false,
  recu            boolean NOT NULL DEFAULT false,
  date_reception  timestamptz,
  receptionne_par integer REFERENCES utilisateur (id) ON DELETE SET NULL
);
CREATE INDEX ON demande_materiel_lignes (id_document);
CREATE INDEX ON demande_materiel_lignes (receptionne_par);


-- ---------------------------------------------------------------------------------------
-- Les livraisons et l'approvisionnement
-- ---------------------------------------------------------------------------------------

CREATE TABLE bon_livraison (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_demande       integer NOT NULL REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  numero           varchar(40) NOT NULL UNIQUE,
  fournisseur      varchar(120) NOT NULL,
  date_bl          date,
  date_livraison_2 date,
  lieu_livraison   varchar(255),
  statut           text NOT NULL DEFAULT 'attendu' CHECK (statut IN ('attendu', 'partielle', 'complete', 'refusee')),
  commentaire      varchar(1000),
  receptionne_par  integer REFERENCES utilisateur (id) ON DELETE SET NULL,
  date_reception   timestamptz,
  revision         integer NOT NULL DEFAULT 0,
  date_creation    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON bon_livraison (id_demande);
CREATE INDEX ON bon_livraison (receptionne_par);
COMMENT ON COLUMN bon_livraison.date_livraison_2 IS 'seconde échéance quand la commande arrive en deux fois';
COMMENT ON COLUMN bon_livraison.lieu_livraison IS 'où la marchandise arrive, repris de l''adresse de livraison du bon';

CREATE TABLE bon_livraison_ligne (
  id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_bon            integer NOT NULL REFERENCES bon_livraison (id) ON DELETE CASCADE,
  ordre             integer NOT NULL DEFAULT 0,
  reference_article varchar(80),
  designation       varchar(180) NOT NULL,
  unite             varchar(16) NOT NULL DEFAULT 'u',
  quantite_attendue numeric(12,3) NOT NULL,
  quantite_recue    numeric(12,3),
  commentaire       varchar(500)
);
CREATE INDEX ON bon_livraison_ligne (id_bon);

CREATE TABLE demande_approvisionnement (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_demande      integer NOT NULL REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  id_ligne_bl     integer REFERENCES bon_livraison_ligne (id) ON DELETE SET NULL,
  designation     varchar(180) NOT NULL,
  quantite        numeric(12,3) NOT NULL,
  unite           varchar(16) NOT NULL DEFAULT 'u',
  motif           text NOT NULL CHECK (motif IN ('oubli', 'erreur', 'fabrication', 'autre')),
  commentaire     varchar(1000),
  demande_par     integer NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
  date_creation   timestamptz NOT NULL DEFAULT now(),
  statut          text NOT NULL DEFAULT 'nouvelle' CHECK (statut IN ('nouvelle', 'vue', 'traitee')),
  traite_par      integer REFERENCES utilisateur (id) ON DELETE SET NULL,
  date_traitement timestamptz
);
CREATE INDEX ON demande_approvisionnement (id_demande);
CREATE INDEX ON demande_approvisionnement (statut);
CREATE INDEX ON demande_approvisionnement (id_ligne_bl);
CREATE INDEX ON demande_approvisionnement (demande_par);
CREATE INDEX ON demande_approvisionnement (traite_par);


-- ---------------------------------------------------------------------------------------
-- L'atelier
-- ---------------------------------------------------------------------------------------

CREATE TABLE element_atelier (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_demande    integer NOT NULL REFERENCES demande_prefabrication (id) ON DELETE CASCADE,
  reference     varchar(80) NOT NULL,
  libelle       varchar(180) NOT NULL,
  cree_par      integer NOT NULL REFERENCES utilisateur (id),
  date_creation timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_demande, reference)
);
CREATE INDEX ON element_atelier (cree_par);

CREATE TABLE element_atelier_document (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_element    integer NOT NULL REFERENCES element_atelier (id) ON DELETE CASCADE,
  type_document text NOT NULL CHECK (type_document IN ('plan', 'qmos', 'dmos')),
  cle_document  varchar(255) NOT NULL,
  pages         integer NOT NULL DEFAULT 1,
  numeros_ligne jsonb,
  UNIQUE (id_element, type_document, cle_document)
);
COMMENT ON COLUMN element_atelier_document.numeros_ligne IS 'numéro de ligne du cartouche, par page : {"1":"YU-PRE-101"}';

CREATE TABLE element_atelier_etapes (
  id_element        integer PRIMARY KEY REFERENCES element_atelier (id) ON DELETE CASCADE,
  statuts           jsonb NOT NULL,
  revision          integer NOT NULL DEFAULT 1,
  modifie_par       integer NOT NULL REFERENCES utilisateur (id),
  date_modification timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON element_atelier_etapes (modifie_par);

CREATE TABLE element_atelier_etapes_historique (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_element  integer NOT NULL REFERENCES element_atelier (id) ON DELETE CASCADE,
  statuts     jsonb NOT NULL,
  revision    integer NOT NULL,
  modifie_par integer NOT NULL REFERENCES utilisateur (id),
  date_saisie timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_element, revision)
);
CREATE INDEX ON element_atelier_etapes_historique (modifie_par);

CREATE TABLE affectation_atelier (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_element           integer NOT NULL REFERENCES element_atelier (id) ON DELETE CASCADE,
  id_utilisateur       integer NOT NULL REFERENCES utilisateur (id),
  type_affectation     text NOT NULL CHECK (type_affectation IN ('plan', 'montage', 'soudage')),
  affecte_par          integer NOT NULL REFERENCES utilisateur (id),
  date_affectation     timestamptz NOT NULL DEFAULT now(),
  actif                boolean DEFAULT true,
  date_fin_affectation timestamptz,
  avancement           smallint NOT NULL DEFAULT 0 CHECK (avancement <= 100),
  commentaire          text,
  revision             integer NOT NULL DEFAULT 0,
  UNIQUE (id_element, type_affectation, actif)
);
CREATE INDEX ON affectation_atelier (id_utilisateur, actif);
CREATE INDEX ON affectation_atelier (affecte_par);
COMMENT ON COLUMN affectation_atelier.actif IS 'true : l''affectation en cours ; NULL : terminée. Un NULL ne compte pas dans l''unicité : une seule affectation en cours par élément et par type, autant de terminées qu''il en faut';

CREATE TABLE affectation_metier (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_element       integer NOT NULL REFERENCES element_atelier (id) ON DELETE CASCADE,
  id_utilisateur   integer NOT NULL REFERENCES utilisateur (id),
  metier           text NOT NULL CHECK (metier IN ('debit', 'assemblage', 'pointage', 'soudage', 'passivation')),
  affecte_par      integer NOT NULL REFERENCES utilisateur (id),
  date_affectation timestamptz NOT NULL DEFAULT now(),
  UNIQUE (id_element, id_utilisateur, metier)
);
CREATE INDEX ON affectation_metier (id_utilisateur);
CREATE INDEX ON affectation_metier (affecte_par);

CREATE TABLE avancement_atelier (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_affectation  integer NOT NULL REFERENCES affectation_atelier (id) ON DELETE CASCADE,
  id_utilisateur  integer NOT NULL REFERENCES utilisateur (id),
  avancement      smallint NOT NULL CHECK (avancement <= 100),
  soudures        integer,
  soudures_total  integer,
  etapes          smallint,
  etapes_total    smallint,
  commentaire     text,
  etat            text NOT NULL DEFAULT 'valide' CHECK (etat IN ('propose', 'valide', 'refuse')),
  valide_par      integer REFERENCES utilisateur (id) ON DELETE SET NULL,
  date_validation timestamptz,
  date_saisie     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON avancement_atelier (id_utilisateur);
CREATE INDEX ON avancement_atelier (valide_par);
CREATE INDEX ON avancement_atelier (id_affectation, etat, id);

CREATE TABLE pointage_atelier (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_affectation integer NOT NULL REFERENCES affectation_atelier (id) ON DELETE CASCADE,
  id_document    integer REFERENCES element_atelier_document (id) ON DELETE SET NULL,
  page           integer NOT NULL DEFAULT 1,
  id_utilisateur integer NOT NULL REFERENCES utilisateur (id),
  date_travail   date NOT NULL,
  duree_minutes  integer NOT NULL CHECK (duree_minutes > 0 AND duree_minutes <= 1440),
  type_soudure   varchar(30) NOT NULL DEFAULT '',
